import { randomUUID } from "node:crypto";
import { access, readFile, readdir, realpath, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import TOML from "@iarna/toml";
import { isInside, type HarnessManifest } from "./model.js";

const MARKER = "# Generated by Harness Workspace Manager from a user-selected Harness source.\n";
export const CODEX_PROFILE_NAME = "hwm-source";

export async function codexSourceProfile(manifest: HarnessManifest): Promise<string> {
  const sourceConfig = path.join(manifest.workspacePath, ".codex", "config.toml");
  let parsed: Record<string, unknown> = {};
  try {
    const canonicalConfig = await realpath(sourceConfig);
    if (!isInside(manifest.workspacePath, canonicalConfig)) throw new Error("source config leaves Harness root");
    const contents = await readFile(sourceConfig, "utf8");
    const value: unknown = TOML.parse(contents);
    if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("not a TOML table");
    parsed = value as Record<string, unknown>;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
      throw new Error(`Cannot use Harness source config ${sourceConfig}; review its TOML and unsupported keys.`);
    }
  }

  const allowed = new Set(["mcp_servers", "skills", "hooks", "agents", "plugins"]);
  const unsupported = Object.keys(parsed).filter((key) => !allowed.has(key));
  if (unsupported.length) {
    throw new Error(`Harness source config contains keys that cannot be promoted to a user profile: ${unsupported.join(", ")}. Use a Harness launcher instead.`);
  }

  const skillsRoot = path.join(manifest.workspacePath, "skills");
  const skillEntries: Array<{ path: string; enabled: boolean }> = [];
  try {
    for (const entry of await readdir(skillsRoot, { withFileTypes: true })) {
      const skillPath = path.join(skillsRoot, entry.name);
      if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
      const canonical = await realpath(skillPath);
      if (!isInside(manifest.workspacePath, canonical) || !(await stat(canonical)).isDirectory()) continue;
      try { await access(path.join(canonical, "SKILL.md")); }
      catch { continue; }
      skillEntries.push({ path: canonical, enabled: true });
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw new Error(`Cannot read Harness skills under ${skillsRoot}.`);
  }

  if (!Object.keys(parsed).length && !skillEntries.length) throw new Error(`No Codex config or skills were found in ${manifest.workspacePath}.`);
  if (skillEntries.length) {
    const skills = parsed.skills === undefined ? {} : parsed.skills;
    if (!skills || typeof skills !== "object" || Array.isArray(skills)) throw new Error("Harness skills config must be a TOML table.");
    const skillTable = skills as Record<string, unknown>;
    const existing = skillTable.config === undefined ? [] : skillTable.config;
    if (!Array.isArray(existing)) throw new Error("Harness skills.config must be an array of tables.");
    const configured = new Set(existing.map((item) => typeof item === "object" && item !== null ? (item as Record<string, unknown>).path : undefined));
    parsed.skills = { ...skillTable, config: [...existing, ...skillEntries.filter((item) => !configured.has(item.path))] };
  }
  try { return `${MARKER}${TOML.stringify(parsed as TOML.JsonMap)}`; }
  catch { throw new Error("Harness source config could not be rendered as a Codex profile."); }
}

export async function writeCodexSourceProfile(manifest: HarnessManifest, contents: string): Promise<void> {
  const destination = path.join(manifest.configDirectory, `${CODEX_PROFILE_NAME}.config.toml`);
  try {
    const current = await readFile(destination, "utf8");
    if (!current.startsWith(MARKER)) throw new Error(`Refusing to replace an unmanaged profile: ${destination}`);
    if (current === contents) return;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  const temporary = `${destination}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, contents, { encoding: "utf8", mode: 0o600, flag: "wx" });
    await rename(temporary, destination);
  } catch (error) {
    await rm(temporary, { force: true }).catch(() => undefined);
    throw error;
  }
}
